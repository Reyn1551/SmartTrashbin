# Convert HTML sources into PROGMEM string headers for the ESP32 firmware.
#
# Why a script instead of copy-pasting by hand:
#   - The HTML contains double quotes (") and backslashes (\) that would have
#     to be escaped in C++, and a missed escape breaks the build or the page.
#   - A raw string literal R"rawliteral(...)rawliteral" needs almost no
#     escaping, but it ends early if the HTML ever contains the closing
#     sequence. This script checks for that and refuses to write the header.
#
# Run: python konversi-html.py

import sys
from pathlib import Path

HERE = Path(__file__).parent

# (source HTML, destination header, C++ symbol, what the page serves)
PAGES = [
    ("controller-wifi.html", "web_ui.h",     "INDEX_HTML",   "/ at 192.168.4.1, the control panel"),
    ("debug-page.html",      "debug_ui.h",   "DEBUG_HTML",   "/debug, the diagnostics page"),
    ("setting-page.html",    "setting_ui.h", "SETTING_HTML", "/setting, the settings page"),
]

DELIM = "rawliteral"


def build_header(symbol: str, what: str, html: str, src_name: str, dst_name: str) -> str:
    nlines = html.count("\n") + 1
    nbytes = len(html.encode("utf-8"))

    # Guard and header comment both follow the FILE we are writing, so they stay
    # right if a page is renamed.
    guard = dst_name.upper().replace(".", "_").replace("-", "_")

    return f"""// ============================================================
//  {dst_name}  --  GENERATED by konversi-html.py
//  DO NOT EDIT. Edit {src_name} and run: python konversi-html.py
//
//  Source : {src_name} ({nbytes} bytes, {nlines} lines)
//  Serves : {what}
// ============================================================

#ifndef {guard}
#define {guard}

#include <Arduino.h>

const char {symbol}[] PROGMEM = R"{DELIM}({html}){DELIM}";

#endif  // {guard}
"""


def main() -> int:
    closer = ")" + DELIM + '"'
    failures = 0

    for src_name, dst_name, symbol, what in PAGES:
        src = HERE / src_name
        dst = HERE / dst_name

        if not src.exists():
            print(f"ERROR: {src_name} not found", file=sys.stderr)
            failures += 1
            continue

        html = src.read_text(encoding="utf-8")

        if closer in html:
            print(f"ERROR: {src_name} contains the raw-literal delimiter {closer!r}.", file=sys.stderr)
            print("       Change DELIM in this script or remove that sequence.", file=sys.stderr)
            failures += 1
            continue

        # '??' can form a trigraph on some older compilers.
        if "??" in html:
            print(f"WARNING: {src_name} contains '??', a possible trigraph.", file=sys.stderr)

        dst.write_text(build_header(symbol, what, html, src_name, dst_name),
                       encoding="utf-8")

        nlines = html.count("\n") + 1
        nbytes = len(html.encode("utf-8"))
        print(f"OK  {src_name} -> {dst_name}  ({nbytes} bytes, {nlines} lines)")

    if failures:
        print(f"\n{failures} page(s) failed.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
